def generate_invoice_number():
    last_invoice = Invoice.objects.order_by('-id').first()
    if not last_invoice:
        return 'INV-000001'
    return f'INV-{last_invoice.id + 1:06d}'


def generate_lease_number():
    last_lease = LeaseAgreement.objects.order_by('-id').first()
    if not last_lease:
        return 'LSA-000001'
    return f'LSA-{last_lease.id + 1:06d}'


